import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');

const layout=read('app/layout.js');
const css=read('app/big-moon-valley-account.css');
const auth=read('app/auth/page.js');
const verificationRequest=read('app/api/auth/verification/request/route.js');
const verificationVerify=read('app/api/auth/verification/verify/route.js');
const verificationEngine=read('lib/verification/server.js');
const sessionRoute=read('app/api/auth/session/route.js');
const sessionEngine=read('lib/auth/laneriq-session.js');
const authCss=read('app/auth/auth.css');
const projects=read('app/my-apps/page.js');

const projectRoot='main.page:has(>header .owner)';
const allowedRoots=['.authPage','.loadingScreen',projectRoot];

assert.match(layout,/import "\.\/big-moon-valley-workspace\.css";\s*import "\.\/big-moon-valley-account\.css";/,'Account shell must load after the workspace shell');
assert.match(css,/url\('\/big-moon-valley\.svg'\)/,'Account shell must use the Big Moon Valley signature scene');
assert.match(css,/padding-top:clamp\(145px,20svh,235px\)/,'Desktop Auth must preserve a cinematic landscape zone');
assert.match(css,/padding-top:clamp\(150px,22svh,250px\)/,'Desktop My Projects must preserve a cinematic landscape zone');
assert.match(css,/padding-top:clamp\(205px,33svh,285px\)/,'Phone My Projects must preserve a larger signature zone');
assert.match(css,/env\(safe-area-inset-top\)/,'Account shell must respect the iPhone top safe area');
assert.match(css,/env\(safe-area-inset-bottom\)/,'Account shell must respect the iPhone bottom safe area');
assert.match(css,/font-size:16px!important/,'Auth inputs must retain iPhone-safe input sizing');
assert.match(css,/min-height:48px!important/,'Primary account actions must retain mobile-friendly touch targets');
assert.match(css,/backdrop-filter:blur\(30px\) saturate\(1\.09\)/,'Auth card must retain premium glass depth');
assert.match(css,/@media\(max-width:520px\)/,'Dedicated phone account composition is required');
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/,'Account shell must respect reduced-motion preference');

const clean=css.replace(/\/\*[\s\S]*?\*\//g,'');
assert.ok(!clean.includes('/a/'),'Account visual CSS must never target generated App routes');
assert.ok(!clean.includes('/website/'),'Account visual CSS must never target generated Website routes');
let selectorCount=0;
for(const match of clean.matchAll(/([^{}]+)\{/g)){
  const header=match[1].trim();
  if(!header||header.startsWith('@'))continue;
  for(const selector of header.split(',')){
    const s=selector.trim();
    selectorCount+=1;
    assert.ok(allowedRoots.some(root=>s.startsWith(root)),`Unscoped selector is forbidden in account shell: ${s}`);
  }
}
assert.ok(selectorCount>=70,'Account selector scope check must cover the full Auth/My Projects visual layer');

assert.match(auth,/const WHATSAPP_AUTH_ENABLED = process\.env\.NEXT_PUBLIC_WHATSAPP_AUTH_ENABLED === "true";/,'WhatsApp must be controlled by the dedicated environment flag');
assert.match(auth,/if \(value === "whatsapp" && !WHATSAPP_AUTH_ENABLED\) return;/,'Unconfigured WhatsApp must remain non-selectable');
assert.match(auth,/disabled=\{!WHATSAPP_AUTH_ENABLED\}/,'WhatsApp tab must fail closed until the managed delivery path is ready');
assert.match(auth,/WHATSAPP_AUTH_ENABLED \? "READY" : "SETUP"/,'WhatsApp status must be explicit');
assert.match(auth,/Email Code/,'Email Code must remain available');
assert.match(auth,/WhatsApp Code/,'WhatsApp Code must be the only phone verification option');
assert.match(auth,/<b>LANERIQ<\/b>/,'Email Code must identify the LANERIQ-owned verification path');
assert.doesNotMatch(auth,/<strong>SMS Code<\/strong>/,'Paid SMS must not remain as a customer verification option');
assert.doesNotMatch(auth,/process\.env\.NEXT_PUBLIC_SMS_AUTH_ENABLED|const\s+SMS_AUTH_ENABLED\s*=/,'Retired SMS feature flag must never be active');
assert.doesNotMatch(auth,/switchMethod\("sms"\)/,'Retired SMS method must not be selectable');
assert.match(auth,/No paid SMS fallback is used/,'Auth UI must explicitly forbid paid SMS fallback');
assert.match(auth,/fetch\("\/api\/auth\/verification\/request"/,'Email/WhatsApp code requests must go through the LANERIQ Verification backend');
assert.match(auth,/fetch\("\/api\/auth\/verification\/verify"/,'Email Code verification must go through the LANERIQ-owned verifier');
assert.doesNotMatch(auth,/auth\.signInWithOtp/,'Browser Auth UI must not generate OTPs directly');
assert.doesNotMatch(auth,/verifyOtp\(\{ email:/,'Browser Auth UI must not verify Email OTP through Supabase Auth');
assert.match(verificationRequest,/requestLaneriqEmailVerification/,'Email OTP generation/delivery must be LANERIQ-owned');
assert.doesNotMatch(verificationRequest,/signInWithOtp\(\{email:/,'Email OTP must no longer be generated by Supabase Auth');
assert.match(verificationRequest,/supabase\.auth\.signInWithOtp\(\{phone:identifier,options\}\)/,'WhatsApp compatibility authority remains behind LANERIQ Verification until migrated');
assert.match(verificationVerify,/verifyLaneriqEmailVerification/,'Email OTP validation must be LANERIQ-owned');
assert.match(verificationVerify,/sessionAuthority:"laneriq"/,'Email verification must create LANERIQ primary session');
assert.match(verificationEngine,/crypto\.randomInt/,'LANERIQ must generate Email OTP cryptographically');
assert.match(verificationEngine,/createHmac\("sha256"/,'LANERIQ must store verification secrets as HMACs');
assert.match(verificationEngine,/createLaneriqSession\(prepared\.userId\)/,'Verified Email must mint LANERIQ primary session');
assert.match(auth,/supabase\.auth\.verifyOtp\(\{ phone: normalizePhoneNumber\(identifier\), token, type: "sms" \}\)/,'Internal phone OTP compatibility protocol remains intact while customer delivery stays WhatsApp-only');
assert.match(auth,/upgradeVerifiedCompatibilitySession\(\)/,'Fresh WhatsApp compatibility verification must upgrade into LANERIQ Session');
assert.doesNotMatch(auth,/supabase\.auth\.getUser\(\)/,'Browser Auth must not trust the compatibility identity as primary session truth');
const whatsappVerify=auth.indexOf('supabase.auth.verifyOtp({ phone:');
const laneriqUpgrade=auth.indexOf('await upgradeVerifiedCompatibilitySession()');
assert.ok(whatsappVerify>=0&&laneriqUpgrade>whatsappVerify,'WhatsApp OTP must succeed before LANERIQ Session upgrade');
assert.match(sessionRoute,/requireFreshSignIn:true/,'WhatsApp session upgrade must require recent verified compatibility identity');
assert.match(sessionRoute,/FRESH_VERIFICATION_REQUIRED/,'Stale compatibility identity must fail closed');
assert.match(sessionRoute,/sessionAuthority:"laneriq"/,'Session API must expose LANERIQ as primary authority');
assert.match(sessionEngine,/LANERIQ_SESSION_COOKIE="laneriq_session"/,'LANERIQ primary cookie contract must exist');
assert.match(auth,/safeInternalNext\(searchParams\.get\("next"\)\)/,'Auth redirect target must remain internally sanitized');
assert.match(authCss,/\.inputWrap input[\s\S]*font-size:16px/,'Base Auth CSS must keep iPhone-safe input sizing even without the shell override');

assert.doesNotMatch(projects,/AI APP BUILDER/,'My Projects must not show the retired AI APP BUILDER brand');
assert.match(projects,/className="eyebrow">LANERIQ AI</,'My Projects must use LANERIQ AI branding');
assert.match(projects,/supabase\.auth\.getUser\(\)/,'My Projects may use the temporary compatibility identity only for existing RLS/data access after proxy authentication');
assert.match(projects,/if \(!user\) redirect\("\/auth"\)/,'Unavailable compatibility data access must fail closed');
assert.match(projects,/\.eq\("owner_id", user\.id\)/,'My Projects query must remain owner-scoped');
assert.match(projects,/await revokeLaneriqSessionToken\(token\)/,'My Projects sign-out must revoke LANERIQ primary session');
assert.match(projects,/redirect\("\/my-apps\?logout_error=session_revoke_unavailable"\)/,'My Projects logout must fail closed if LANERIQ revocation cannot be confirmed');
assert.match(projects,/await client\.auth\.signOut\(\{ scope: "local" \}\)/,'Compatibility session cleanup must remain downstream of LANERIQ revoke');
assert.match(projects,/cookieStore\.set\(LANERIQ_SESSION_COOKIE, "", laneriqSessionClearCookieOptions\(\)\)/,'LANERIQ cookie must be cleared only after authoritative revoke');
assert.match(projects,/cookieStore\.set\(LANERIQ_SESSION_MODE_COOKIE, LANERIQ_SESSION_MODE_VALUE/,'Primary marker must remain after logout to block stale compatibility resurrection');
const projectRevoke=projects.indexOf('await revokeLaneriqSessionToken(token)');
const projectCompatSignOut=projects.indexOf('await client.auth.signOut({ scope: "local" })');
const projectClear=projects.indexOf('cookieStore.set(LANERIQ_SESSION_COOKIE, "", laneriqSessionClearCookieOptions())');
assert.ok(projectRevoke>=0&&projectCompatSignOut>projectRevoke&&projectClear>projectCompatSignOut,'My Projects logout order must be LANERIQ revoke → compatibility cleanup → cookie clear');
assert.match(projects,/href=\{`\/a\/\$\{app\.id\}\?demo=1`\}/,'Generated App demo navigation must remain separate from LANERIQ shell styling');
assert.match(projects,/href=\{`\/website\/\$\{app\.id\}`\}/,'Generated Website navigation must remain separate from LANERIQ shell styling');

console.log('✓ Big Moon Valley carries through LANERIQ-owned Email OTP and LANERIQ-primary account sessions');
console.log(`✓ ${selectorCount} account-shell selectors are scoped only to Auth/loading/My Projects roots`);
console.log('✓ Email Code is LANERIQ-generated/verified; WhatsApp compatibility verification explicitly upgrades to LANERIQ Session');
console.log('✓ My Projects keeps owner-scoped transitional data access while logout revokes LANERIQ authority first and fails closed');