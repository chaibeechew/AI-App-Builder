import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd();
const integrations=fs.readFileSync(path.join(root,'lib/integrations/server.js'),'utf8');
const provider=fs.readFileSync(path.join(root,'lib/email-provider/server.js'),'utf8');
const productionSync=fs.readFileSync(path.join(root,'.github/workflows/email-delivery-production-sync.yml'),'utf8');

assert.match(integrations,/import net from "node:net"/,'Managed SMTP must support STARTTLS transports.');
assert.match(integrations,/import tls from "node:tls"/,'Managed SMTP must use TLS.');
assert.match(integrations,/function smtpReady\(\)/);
assert.match(integrations,/process\.env\.SMTP_HOST&&process\.env\.SMTP_USER&&process\.env\.SMTP_PASS&&process\.env\.EMAIL_FROM/);
assert.match(integrations,/function resendReady\(\)/);
assert.match(integrations,/process\.env\.RESEND_API_KEY&&process\.env\.EMAIL_FROM/);
assert.match(integrations,/email:\{ready:smtpReady\(\)\|\|resendReady\(\),managed:true\}/,'Email readiness must accept either managed transport.');
assert.match(integrations,/tls\.connect\(\{host,port,servername:host,rejectUnauthorized:true\}\)/,'Implicit SMTP TLS certificate validation must stay enabled.');
assert.match(integrations,/tls\.connect\(\{socket:raw,servername:host,rejectUnauthorized:true\}/,'STARTTLS upgrade must validate the SMTP certificate.');
assert.match(integrations,/raw\.write\("STARTTLS\\r\\n"\)/,'SMTP port 587/25 must upgrade with STARTTLS before authentication.');
assert.match(integrations,/AUTH PLAIN/);
assert.match(integrations,/AUTH LOGIN/,'SMTP must fall back to AUTH LOGIN when AUTH PLAIN is not accepted.');
assert.match(integrations,/function smtpPassword/,'SMTP password normalization must be explicit and bounded to known providers.');
assert.match(integrations,/smtp\.gmail\.com/,'Gmail App Password compatibility must remain explicit.');
assert.match(integrations,/pass\.replace\(\/\\s\+\/g,""\)/,'Gmail App Password display whitespace must not break SMTP authentication.');
assert.match(integrations,/function safeHeader/,'SMTP header sanitizer must exist.');
assert.ok(integrations.includes('replace(/[\\r\\n]+/g," ")'),'SMTP headers must strip CR/LF before protocol framing.');
assert.match(integrations,/function mailbox/,'SMTP envelope addresses must be validated.');
assert.match(integrations,/function smtpFailure\(code\)/,'SMTP stage failures must be classified without provider text.');
assert.match(integrations,/"smtp_auth_failed"/,'SMTP authentication failures must have a safe diagnostic code.');
assert.match(integrations,/"smtp_starttls_failed"/,'STARTTLS failures must have a safe diagnostic code.');
assert.match(integrations,/"smtp_sender_rejected"/,'Sender rejection must be distinguishable without exposing SMTP responses.');
assert.match(integrations,/"smtp_recipient_rejected"/,'Recipient rejection must be distinguishable without exposing SMTP responses.');
assert.match(provider,/SAFE_TRANSPORT_ERROR_CODES/,'LANERIQ Email Provider must explicitly allow safe transport diagnostics.');
assert.match(provider,/function safeTransportErrorCode\(error\)/,'LANERIQ Email Provider must sanitize transport errors before persistence.');
assert.doesNotMatch(provider,/error\?\.message.*last_error|provider_response|smtp_response/i,'Provider response text must not be persisted with email queue state.');
assert.match(integrations,/if\(smtpReady\(\)\)return sendManagedSmtpEmail\(payload\)/);
assert.match(integrations,/if\(resendReady\(\)\)return sendManagedResendEmail\(payload\)/);
assert.doesNotMatch(integrations,/console\.(log|info|warn|error|debug)/,'Email credentials and OTP payloads must never be logged by the adapter.');
assert.doesNotMatch(integrations,/sendManagedSms|TWILIO|api\.twilio/i,'Paid SMS fallback must remain absent.');
assert.match(integrations,/line_items\[0\]\[price_data\]\[unit_amount\]/,'Email adapter changes must not regress Stripe checkout amount encoding.');

assert.ok(productionSync.includes('GMAIL_USER: ${{ secrets.GMAIL_USER }}'),'Production sync must accept a Gmail account secret.');
assert.ok(productionSync.includes('GMAIL_APP_PASSWORD: ${{ secrets.GMAIL_APP_PASSWORD }}'),'Production sync must accept a Gmail App Password secret.');
assert.ok(productionSync.includes('SMTP_USER: ${{ secrets.SMTP_USER }}'),'Production sync must retain generic SMTP compatibility.');
assert.ok(productionSync.includes('SMTP_PASS: ${{ secrets.SMTP_PASS }}'),'Production sync must retain generic SMTP password compatibility.');
assert.match(productionSync,/smtp\.gmail\.com/,'Gmail mode must resolve the official Gmail SMTP host.');
assert.match(productionSync,/smtp_port="\$\{SMTP_PORT:-465\}"/,'Gmail/SMTPS must default to TLS port 465.');
assert.match(productionSync,/tr -d '\[:space:\]'/,'Pasted Gmail App Password grouping whitespace must be removed before synchronization.');
assert.match(productionSync,/key:"SMTP_HOST"/);
assert.match(productionSync,/key:"SMTP_USER"/);
assert.match(productionSync,/key:"SMTP_PASS"/);
assert.match(productionSync,/key:"EMAIL_FROM"/);
assert.match(productionSync,/RESEND_API_KEY/,'Resend must remain an optional replaceable transport.');
assert.match(productionSync,/vercel@latest deploy --prod --yes/,'Production must redeploy after email environment synchronization.');
assert.doesNotMatch(productionSync,/echo\s+"?\$\{?(?:SMTP_PASS|GMAIL_APP_PASSWORD|RESEND_API_KEY|VERCEL_TOKEN)/,'Production sync must never echo secret values.');

console.log('✓ LANERIQ Email Delivery supports implicit TLS, STARTTLS SMTP, or Resend transports');
console.log('✓ Gmail SMTP compatibility handles port 587 and display-spaced App Passwords safely');
console.log('✓ SMTP failure stages remain privacy-safe while preserving useful production diagnostics');
console.log('✓ Gmail/SMTP secrets can be synchronized into existing Vercel Production without exposing values');
console.log('✓ Production email env synchronization is followed by a fresh Vercel Production deployment');
console.log('✓ SMTP envelope/header hardening prevents CRLF injection and validates TLS certificates');
console.log('✓ Email delivery changes preserve no-SMS policy and payment checkout contract');
